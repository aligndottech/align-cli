/**
 * `align context inject` - the read-path counterpart to `align check --advisory`.
 *
 * The write path (agent-rules.ts's Pre/PostToolUse hooks) reaches the model on every edit.
 * Nothing reached the model on SESSION START before this - the graph's content only landed
 * if the model chose to open .align/decisions.md or call an MCP tool. This command is what a
 * SessionStart hook shells out to: it prints the already-synced decisions file wrapped in the
 * JSON shape a host's hook reads back, so the content lands whether or not the model asked.
 *
 * Deliberately reads .align/decisions.md rather than fetching the graph itself: `align context
 * sync` already owns that fetch (network, auth, a spinner, a non-zero exit on failure - none of
 * which belong inside a hook that must stay fast and offline-safe). Reusing the file `sync`
 * already writes is "do not reinvent the rendering" taken literally: no rendering logic lives
 * in this file at all.
 *
 * Test List:
 * 1. no .align/decisions.md - prints nothing, exits 0 (fail open: nothing synced yet)
 * 2. .align/decisions.md present - prints the SessionStart hookSpecificOutput JSON, one line
 * 3. the injected content is the file's content, not a rendering of it (parse the JSON back)
 * 4. whitespace-only file - prints nothing (an empty additionalContext is not worth a line)
 * 5. never throws on an unreadable file - fails open like every other host shim in this repo
 */
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { Command } from 'commander';
import fs from 'node:fs';
import { Readable } from 'node:stream';
import os from 'node:os';
import path from 'node:path';
// The local-graph fallback is its own module (context-from-graph.test.ts). Mocked here so no test can read this machine's real graph:
// null by default, which is "no local graph", so every case below that predates the fallback keeps its meaning.
const fromGraph = vi.hoisted(() => vi.fn());
vi.mock('../lib/context-from-graph.js', () => ({ decisionsFromLocalGraph: fromGraph }));
import { registerContextCommand } from '../commands/context.js';
import { externalContextPath } from '../lib/decisions-context.js';

let repo: string;
let prevCwd: string;

beforeEach(() => {
  repo = fs.mkdtempSync(path.join(os.tmpdir(), 'ali933-inject-'));
  prevCwd = process.cwd();
  process.chdir(repo);
  fromGraph.mockReset().mockResolvedValue(null);
});

afterEach(() => {
  process.chdir(prevCwd);
  fs.rmSync(repo, { recursive: true, force: true });
  vi.restoreAllMocks();
});

async function runInject(extra: string[] = [], stdin?: string): Promise<{ stdout: string }> {
  const program = new Command();
  program.exitOverride();
  registerContextCommand(program);
  let stdout = '';
  const writeSpy = vi.spyOn(process.stdout, 'write').mockImplementation((chunk: unknown) => {
    stdout += String(chunk);
    return true;
  });
  const stdinSpy = stdin === undefined ? null : vi.spyOn(process, 'stdin', 'get').mockReturnValue(Readable.from([stdin]) as unknown as typeof process.stdin);
  try {
    await program.parseAsync(['node', 'align', 'context', 'inject', ...extra]);
  } finally {
    stdinSpy?.mockRestore();
    writeSpy.mockRestore();
  }
  return { stdout };
}

describe('align context inject', () => {
  it('prints nothing when .align/decisions.md has never been synced', async () => {
    const { stdout } = await runInject();
    expect(stdout).toBe('');
  });

  it('prints the SessionStart hookSpecificOutput JSON when the file exists', async () => {
    fs.mkdirSync(path.join(repo, '.align'), { recursive: true });
    fs.writeFileSync(path.join(repo, '.align', 'decisions.md'), '# Decisions\n\n- Use Postgres 16\n');
    const { stdout } = await runInject();
    const lines = stdout.trim().split('\n');
    expect(lines).toHaveLength(1);
    const parsed = JSON.parse(lines[0]);
    expect(parsed).toHaveProperty('hookSpecificOutput.hookEventName', 'SessionStart');
    expect(typeof parsed.hookSpecificOutput.additionalContext).toBe('string');
  });

  it('injects the raw file content, not a re-rendering of it', async () => {
    const content = '# Decisions (generated by Align)\n\n- Use Postgres 16 (api#1441) - https://github.com/x\n';
    fs.mkdirSync(path.join(repo, '.align'), { recursive: true });
    fs.writeFileSync(path.join(repo, '.align', 'decisions.md'), content);
    const { stdout } = await runInject();
    const parsed = JSON.parse(stdout.trim());
    expect(parsed.hookSpecificOutput.additionalContext).toBe(content.trimEnd());
  });

  it('preserves leading whitespace inside the file - only trailing newlines are stripped', async () => {
    // An indented code block on the first line is real markdown; a naive full-string
    // .trim() would strip it and contradict the "raw file content" claim above.
    const content = '    indented first line\n\n- Use Postgres 16\n\n\n';
    fs.mkdirSync(path.join(repo, '.align'), { recursive: true });
    fs.writeFileSync(path.join(repo, '.align', 'decisions.md'), content);
    const { stdout } = await runInject();
    const parsed = JSON.parse(stdout.trim());
    expect(parsed.hookSpecificOutput.additionalContext).toBe('    indented first line\n\n- Use Postgres 16');
  });

  it('prints nothing for a whitespace-only decisions file', async () => {
    fs.mkdirSync(path.join(repo, '.align'), { recursive: true });
    fs.writeFileSync(path.join(repo, '.align', 'decisions.md'), '   \n\n\t\n');
    const { stdout } = await runInject();
    expect(stdout).toBe('');
  });

  it('fails open (no throw, no output) when the file cannot be read as UTF-8 text', async () => {
    // A directory named decisions.md is unreadable as text - stands in for any read error
    // that isn't ENOENT, without needing to fake filesystem permissions cross-platform.
    fs.mkdirSync(path.join(repo, '.align', 'decisions.md'), { recursive: true });
    await expect(runInject()).resolves.toEqual({ stdout: '' });
  });
});

// A normal setup never writes .align/decisions.md (only `align context sync` does), so without this the hook printed nothing
// and the agent started every session blind. With no file, a local graph is read directly.
describe('align context inject, no decisions file', () => {
  const GRAPH = '# Decisions (generated by Align)\n\n- Retry webhooks three times with backoff\n';

  it('injects the local graph\'s decisions when the repo has no decisions file', async () => {
    fromGraph.mockResolvedValue(GRAPH);
    const { stdout } = await runInject();
    expect(JSON.parse(stdout.trim()).hookSpecificOutput.additionalContext).toBe(GRAPH.trimEnd());
    expect(fs.realpathSync(fromGraph.mock.calls[0]![0])).toBe(fs.realpathSync(repo));
  });

  it('a decisions file, when there is one, wins over the graph, and the graph is not read', async () => {
    fromGraph.mockResolvedValue(GRAPH);
    fs.mkdirSync(path.join(repo, '.align'), { recursive: true });
    fs.writeFileSync(path.join(repo, '.align', 'decisions.md'), '# Decisions\n\n- Use Postgres 16\n');
    const { stdout } = await runInject();
    expect(JSON.parse(stdout.trim()).hookSpecificOutput.additionalContext).toBe('# Decisions\n\n- Use Postgres 16');
    expect(fromGraph).not.toHaveBeenCalled();
  });

  it('codex: reads the graph for the workspace the payload names, not the process cwd', async () => {
    fromGraph.mockResolvedValue(GRAPH);
    const other = fs.mkdtempSync(path.join(os.tmpdir(), 'inject-graph-ws-'));
    try {
      const { stdout } = await runInject(['--format', 'codex'], JSON.stringify({ cwd: other }));
      expect(JSON.parse(stdout.trim()).hookSpecificOutput.additionalContext).toBe(GRAPH.trimEnd());
      expect(fs.realpathSync(fromGraph.mock.calls[0]![0])).toBe(fs.realpathSync(other));
    } finally {
      fs.rmSync(other, { recursive: true, force: true });
    }
  });
});

// The same command now serves the user-level hosts (Codex, Gemini CLI, Copilot CLI).
// Their payload fixtures are the documented shapes, see fixtures/session-start-payloads/README.md.
describe('align context inject --format <host>', () => {
  const content = '# Decisions\n\n- Use Postgres 16';
  const fixture = (name: string): string =>
    fs.readFileSync(path.join(__dirname, 'fixtures', 'session-start-payloads', name), 'utf8');
  const sync = (root: string): void => {
    fs.mkdirSync(path.join(root, '.align'), { recursive: true });
    fs.writeFileSync(path.join(root, '.align', 'decisions.md'), content);
  };

  it.each([['codex', 'codex-session-start.json'], ['gemini', 'gemini-session-start.json']])(
    '%s: nested hookSpecificOutput, reading the workspace named by the payload cwd, not the process cwd',
    async (format, file) => {
      const other = fs.mkdtempSync(path.join(os.tmpdir(), 'ali2130-ws-'));
      try {
        sync(other); // decisions exist ONLY in the payload's workspace; the process cwd (repo) has none
        const payload = JSON.stringify({ ...JSON.parse(fixture(file)), cwd: other });
        const { stdout } = await runInject(['--format', format], payload);
        expect(JSON.parse(stdout.trim())).toEqual({
          hookSpecificOutput: { hookEventName: 'SessionStart', additionalContext: content },
        });
      } finally {
        fs.rmSync(other, { recursive: true, force: true });
      }
    },
  );

  it('copilot: additionalContext is a top-level key, with no hookSpecificOutput wrapper', async () => {
    const other = fs.mkdtempSync(path.join(os.tmpdir(), 'ali2130-ws-'));
    try {
      sync(other);
      const payload = JSON.stringify({ ...JSON.parse(fixture('copilot-session-start.json')), cwd: other });
      const { stdout } = await runInject(['--format', 'copilot'], payload);
      expect(JSON.parse(stdout.trim())).toEqual({ additionalContext: content });
    } finally {
      fs.rmSync(other, { recursive: true, force: true });
    }
  });

  it('cursor: additional_context is a top-level snake_case key, workspace read from workspace_roots', async () => {
    const other = fs.mkdtempSync(path.join(os.tmpdir(), 'ali2130-ws-'));
    try {
      sync(other);
      const payload = JSON.stringify({ ...JSON.parse(fixture('cursor-session-start.json')), workspace_roots: [other] });
      const { stdout } = await runInject(['--format', 'cursor'], payload);
      expect(JSON.parse(stdout.trim())).toEqual({ additional_context: content });
    } finally {
      fs.rmSync(other, { recursive: true, force: true });
    }
  });

  it('cursor: prints nothing when the payload names no existing workspace, even if the process cwd has decisions', async () => {
    sync(repo); // the process cwd (a user-level hook can start in any repo) has decisions
    const missing = JSON.stringify({ workspace_roots: [path.join(repo, 'nope')] });
    expect((await runInject(['--format', 'cursor'], missing)).stdout).toBe('');
    expect((await runInject(['--format', 'cursor'], '{}')).stdout).toBe('');
  });

  it('cursor: a workspace root that is a regular file does not climb to the parent checkout', async () => {
    sync(repo);
    fs.mkdirSync(path.join(repo, '.git'));
    const file = path.join(repo, 'notes.txt');
    fs.writeFileSync(file, 'x');
    const { stdout } = await runInject(['--format', 'cursor'], JSON.stringify({ workspace_roots: [file] }));
    expect(stdout).toBe('');
  });

  const HOSTS: Array<[string, string]> = [
    ['codex', 'codex-session-start.json'],
    ['gemini', 'gemini-session-start.json'],
    ['copilot', 'copilot-session-start.json'],
  ];

  // The payload NAMES a path that is not a usable directory: a stale or deleted workspace. A
  // user-level hook can start in any repo, so falling back to the process cwd would inject
  // another project's decisions.
  it.each(HOSTS)('%s: prints nothing when the payload cwd does not exist, even if the process cwd has decisions', async (format, file) => {
    sync(repo);
    const payload = JSON.stringify({ ...JSON.parse(fixture(file)), cwd: path.join(repo, 'nope') });
    expect((await runInject(['--format', format], payload)).stdout).toBe('');
    const deleted = fs.mkdtempSync(path.join(os.tmpdir(), 'ali2130-gone-'));
    fs.rmSync(deleted, { recursive: true, force: true }); // a workspace that existed and was deleted
    const gone = JSON.stringify({ ...JSON.parse(fixture(file)), cwd: deleted });
    expect((await runInject(['--format', format], gone)).stdout).toBe('');
  });

  it.each(HOSTS)('%s: a payload cwd that is a regular file prints nothing', async (format, file) => {
    sync(repo);
    const target = path.join(repo, 'notes.txt');
    fs.writeFileSync(target, 'x');
    const payload = JSON.stringify({ ...JSON.parse(fixture(file)), cwd: target });
    expect((await runInject(['--format', format], payload)).stdout).toBe('');
  });

  // The payload names NOTHING: the fallback to the process cwd stays, for a host that omits cwd.
  it.each(HOSTS)('%s: falls back to the process cwd when the payload names no cwd at all', async (format) => {
    sync(repo);
    for (const payload of ['{}', JSON.stringify({ cwd: '' }), JSON.stringify({ cwd: 42 })]) {
      const { stdout } = await runInject(['--format', format], payload);
      expect(stdout, payload).toContain('Use Postgres 16');
    }
  });

  it('prints nothing for an unknown format (fails open)', async () => {
    sync(repo);
    expect((await runInject(['--format', 'vim'], '{}')).stdout).toBe('');
  });

  it('finds the project decisions when the host starts the session in a subdirectory', async () => {
    sync(repo);
    fs.mkdirSync(path.join(repo, '.git'));
    const sub = path.join(repo, 'packages', 'app');
    fs.mkdirSync(sub, { recursive: true });
    const { stdout } = await runInject(['--format', 'codex'], JSON.stringify({ cwd: sub }));
    expect(JSON.parse(stdout.trim()).hookSpecificOutput.additionalContext).toBe(content);
  });

  it('prefers a decisions file in the session directory over one further up', async () => {
    sync(repo);
    const sub = path.join(repo, 'pkg');
    fs.mkdirSync(path.join(sub, '.align'), { recursive: true });
    fs.writeFileSync(path.join(sub, '.align', 'decisions.md'), 'nearer');
    const { stdout } = await runInject(['--format', 'codex'], JSON.stringify({ cwd: sub }));
    expect(JSON.parse(stdout.trim()).hookSpecificOutput.additionalContext).toBe('nearer');
  });

  it('does not send a file outside the workspace that .align/decisions.md links to', async () => {
    const secret = path.join(os.tmpdir(), `ali-secret-${process.pid}.txt`);
    fs.writeFileSync(secret, 'SECRET');
    try {
      fs.mkdirSync(path.join(repo, '.align'), { recursive: true });
      const link = path.join(repo, '.align', 'decisions.md');
      try {
        fs.symlinkSync(path.join(repo, 'real.md'), link);
      } catch {
        return; // no symlink permission (Windows without developer mode): nothing to test
      }
      // Control: a link to a file INSIDE the workspace is still injected, so the empty output
      // below comes from the guard and not from a link the hook cannot follow.
      fs.writeFileSync(path.join(repo, 'real.md'), 'inside');
      expect(JSON.parse((await runInject()).stdout.trim()).hookSpecificOutput.additionalContext).toBe('inside');
      fs.rmSync(link);
      fs.symlinkSync(secret, link);
      for (const extra of [[], ['--format', 'codex']]) {
        expect((await runInject(extra, JSON.stringify({ cwd: repo }))).stdout).toBe('');
      }
    } finally {
      fs.rmSync(secret, { force: true });
    }
  });

  // A repo you cloned can link .align/decisions.md at Align's own folder. Only this repo's own
  // private decisions file there may be read: config.json holds tokens when there is no OS
  // credential store, and contexts/ holds other repos' decisions.
  describe('a link into the Align folder', () => {
    let home: string;

    beforeEach(() => {
      home = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'ali-home-')));
      vi.stubEnv('HOME', home);
      vi.stubEnv('USERPROFILE', home);
      fs.mkdirSync(path.join(repo, '.align'), { recursive: true });
    });

    afterEach(() => {
      vi.unstubAllEnvs();
      fs.rmSync(home, { recursive: true, force: true });
    });

    const linkTo = (target: string): boolean => {
      const link = path.join(repo, '.align', 'decisions.md');
      fs.rmSync(link, { force: true });
      try {
        fs.symlinkSync(target, link);
        return true;
      } catch {
        return false; // no symlink permission (Windows without developer mode): nothing to test
      }
    };

    const write = (file: string, text: string): string => {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, text);
      return file;
    };

    it('injects this repo\'s own private decisions file', async () => {
      const own = write(externalContextPath(fs.realpathSync(repo)), 'own decisions');
      if (!linkTo(own)) return;
      for (const extra of [[], ['--format', 'codex']]) {
        const { stdout } = await runInject(extra, JSON.stringify({ cwd: repo }));
        expect(JSON.parse(stdout.trim()).hookSpecificOutput.additionalContext).toBe('own decisions');
      }
    });

    it('injects the repo\'s own file when the host names the workspace through a symlink', async () => {
      // sync keyed the file on the real path; the payload spells the same folder another way.
      const own = write(externalContextPath(fs.realpathSync(repo)), 'own decisions');
      if (!linkTo(own)) return;
      const alias = path.join(home, 'alias');
      fs.symlinkSync(repo, alias);
      const { stdout } = await runInject(['--format', 'codex'], JSON.stringify({ cwd: alias }));
      expect(JSON.parse(stdout.trim()).hookSpecificOutput.additionalContext).toBe('own decisions');
    });

    it('does not send config.json', async () => {
      const config = write(path.join(home, '.align', 'config.json'), '{"connectorTokens":{"github":"TOKEN"}}');
      if (!linkTo(config)) return;
      for (const extra of [[], ['--format', 'codex']]) {
        expect((await runInject(extra, JSON.stringify({ cwd: repo }))).stdout).toBe('');
      }
    });

    it('does not send another repo\'s private decisions file', async () => {
      const other = write(externalContextPath(path.join(home, 'some-other-repo')), 'other repo decisions');
      if (!linkTo(other)) return;
      for (const extra of [[], ['--format', 'codex']]) {
        expect((await runInject(extra, JSON.stringify({ cwd: repo }))).stdout).toBe('');
      }
    });
  });
});
