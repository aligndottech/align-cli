#!/usr/bin/env python3
"""Generate src/detector/relationship-prompt.v1.json from the hosted ANALYSIS_RULES, verbatim.

The shared v1 base is three byte-exact slices of align-stack's
services/brain/app/prompts/change_analysis.py ANALYSIS_RULES (plan Decision 2): the similar[]
item schema line, rules 0 to 3, and the SIMILAR DECISIONS type list. The hosted-only parts
(existing, siblings, missing_evidence, ambiguity, rule 4) are not included.

Usage (no network, the prompt module imports nothing):
  git -C <align-stack> show origin/main:services/brain/app/prompts/change_analysis.py > /tmp/ca.py
  python3 -I scripts/extract-shared-prompt.py --source /tmp/ca.py --commit <sha> > src/detector/relationship-prompt.v1.json
"""
import argparse
import hashlib
import importlib.util
import json


def between(text: str, start: str, end: str) -> str:
    i = text.index(start)
    j = text.index(end, i)
    assert text.count(start) == 1 and text.count(end) == 1, (start, end)
    return text[i:j]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", required=True)
    ap.add_argument("--commit", required=True)
    args = ap.parse_args()
    spec = importlib.util.spec_from_file_location("ca", args.source)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    rules_text = mod.ANALYSIS_RULES

    item_line = next(line for line in rules_text.split("\n") if line.lstrip().startswith('{"decision_ref": <the number of the SIMILAR DECISION above>'))
    item_schema = item_line.strip()
    rules = between(rules_text, "CRITICAL INSTRUCTIONS FOR RELATIONSHIP DETECTION:", "4. **SIBLING DECISIONS").rstrip("\n")
    types = between(rules_text, "Relationship types (SIMILAR DECISIONS):", "\n\nAmbiguity indicators:")
    for piece in (item_schema, rules, types):
        assert piece in rules_text
    print(json.dumps({
        "template": "align.relationship.prompt",
        "version": 1,
        "note": "Generated by scripts/extract-shared-prompt.py. Each section is a byte-exact slice of the hosted ANALYSIS_RULES. Do not hand-edit.",
        "source": "services/brain/app/prompts/change_analysis.py ANALYSIS_RULES",
        "sourceCommit": args.commit,
        "sourceSha256": hashlib.sha256(rules_text.encode("utf-8")).hexdigest(),
        "sections": {"itemSchema": item_schema, "rules": rules, "types": types},
    }, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
