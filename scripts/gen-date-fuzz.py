#!/usr/bin/env python3
"""Generate src/detector/date-fuzz-corpus.json: mutated ISO-ish strings with the brain's verdict.

Each entry is [input, verdict] where verdict is the microseconds since the epoch (a string) that
the brain's parse_decided_at returns, null for None, or "error" when it RAISES instead of
returning None (the TS port must then return null: no date, the safe reading).

Run with the brain image's interpreter (python 3.14), no network:
  git -C <align-stack> show origin/main:services/brain/app/relationship_type_rules.py > /tmp/rtr.py
  python3.14 -I scripts/gen-date-fuzz.py --source /tmp/rtr.py --seed 1 --count 3000 > src/detector/date-fuzz-corpus.json
"""
import argparse
import importlib.util
import json
import random
import sys
from datetime import UTC, datetime


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", required=True)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--count", type=int, default=3000)
    args = ap.parse_args()
    spec = importlib.util.spec_from_file_location("rtr", args.source)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["rtr"] = mod
    spec.loader.exec_module(mod)

    rng = random.Random(args.seed)
    alpha = list("0123456789-:T .,+ZzWx") + ["\n", "\t", " ", "٠", "１", "é", "24", "60", "9999", "0000",
                                              "Z+00:00", "+05:30", "-0130", "+01:00:30.5", "W53", "W00", ".000001", "1234567890"]
    bases = ["2026-01-01T00:00:00Z", "2026-01-01", "2026-W01-1", "2026W011", "20260101T000000", "2026-12-31T23:59:59.999999+14:00",
             "2026-01-01T00:00:00-23:59", "9999-12-31T24:00:00", "2024-02-29T12", "2026-01-01T00:00:00.5Z", "2026-01-01 10:00",
             "2026-W53-7", "0001-01-02T00:00:00+01:00", "2026-01-01T00:00:00,123456789"]

    def mutate(s: str) -> str:
        chars = list(s)
        for _ in range(rng.randint(1, 2)):
            op = rng.random()
            i = rng.randint(0, len(chars))
            if op < 0.4 and chars:
                chars[min(i, len(chars) - 1)] = rng.choice(alpha)
            elif op < 0.7:
                chars.insert(i, rng.choice(alpha))
            elif chars:
                del chars[min(i, len(chars) - 1)]
        return "".join(chars)

    inputs = list(bases) + ["2026-01-01 ", "2026-01-01T", "2026-01-01x", "2026-01-010", "2026-W01-1 ", "2026-01-01é", "2026-01-01é10:00",
              "0001-01-01T00:00:00+23:59", "9999-12-31T23:59:59-23:59", "0001-01-01T00:00:00-23:59", "9999-12-31T23:59:59+23:59"]
    seen = set(inputs)
    while len(inputs) < args.count:
        m = mutate(rng.choice(bases))
        if m not in seen:
            seen.add(m)
            inputs.append(m)
    epoch = datetime(1970, 1, 1, tzinfo=UTC)
    out = []
    for s in inputs:
        try:
            d = mod.parse_decided_at(s)
        except Exception:  # noqa: BLE001 - recorded, not swallowed: the brain raises here
            out.append([s, "error"])
            continue
        if d is None:
            out.append([s, None])
        else:
            delta = d - epoch
            out.append([s, str((delta.days * 86400 + delta.seconds) * 1_000_000 + delta.microseconds)])
    print(json.dumps({"note": "Generated by scripts/gen-date-fuzz.py. Do not hand-edit.", "python": sys.version.split()[0],
                      "seed": args.seed, "cases": out}, ensure_ascii=False, indent=0))


if __name__ == "__main__":
    main()
